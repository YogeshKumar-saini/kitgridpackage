import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const components = join(root, "src", "components")

const dirs = readdirSync(components, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .filter((name) => existsSync(join(components, name, "index.ts")))
  .sort()

const header = "// Generated by scripts/generate.mjs. Do not edit by hand.\n"

const barrel =
  header + dirs.map((name) => `export * from "./${name}/index.js"`).join("\n") + "\n"

const css =
  "/* Generated by scripts/generate.mjs. Do not edit by hand. */\n" +
  dirs
    .flatMap((name) =>
      readdirSync(join(components, name))
        .filter((file) => file.endsWith(".css"))
        .sort()
        .map((file) => `@import "../components/${name}/${file}";`),
    )
    .join("\n") +
  "\n"

const write = (file, content) => {
  if (existsSync(file) && readFileSync(file, "utf8") === content) return
  writeFileSync(file, content)
}

write(join(components, "index.ts"), barrel)
write(join(root, "src", "styles", "components.css"), css)

console.log(`kitgrid: indexed ${dirs.length} components`)
